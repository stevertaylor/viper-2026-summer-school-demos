#!/usr/bin/env python3
"""Build the real-sky assets in shared/sky/ from public catalogs.

Outputs (committed, so the demos stay fully offline):
  shared/sky/milkyway.jpg  diffuse sky, J2000 equatorial plate carree, asinh-encoded
  shared/sky/bsc5.js       Yale Bright Star Catalog, 5th ed.: RA, Dec, V, B-V

Inputs (download once, then run):
  NASA SVS "Deep Star Maps 2020" (ID 4851), celestial-coordinate 4k map:
    https://svs.gsfc.nasa.gov/vis/a000000/a004800/a004851/starmap_2020_4k.exr
    Credit: NASA/Goddard Space Flight Center Scientific Visualization Studio;
    Gaia DR2: ESA/Gaia/DPAC.  Built from Hipparcos-2, Tycho-2 and Gaia DR2.
    Convention (checked against Polaris and Canopus): column c -> RA = 180deg - 360deg (c+.5)/W
    (centred on RA=0h, RA increasing to the LEFT); row r -> Dec = 90deg - 180deg (r+.5)/H.
    Pixel values are LINEAR radiance, clipped to [0,1].
  Yale BSC5 (Hoffleit & Warren 1991), ASCII, same byte layout as CDS V/50:
    http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz

Usage:
  python3 -m venv /tmp/skyenv && /tmp/skyenv/bin/pip install OpenEXR numpy pillow
  /tmp/skyenv/bin/python scripts/build_sky.py starmap_2020_4k.exr bsc5.dat

Encoding of milkyway.jpg (decoded exactly in shared/sky.js):
  each linear channel L in [0, LCLIP] is stored as  E = asinh(L/L0) / asinh(LCLIP/L0)
  in 8 bits (no sRGB curve).  asinh is ~linear below L0 and ~log above, so the faint
  diffuse light keeps its gradation in 8 bits.  LCLIP clips the stellar cores: stars
  brighter than ~V=6.5 are redrawn as crisp point sources from BSC5, so the map only
  needs to carry the diffuse galaxy and the faint, unresolved stars.
"""
import sys, base64, gzip, pathlib
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'shared' / 'sky'
L0, LCLIP = 0.006, 0.25          # must match shared/sky.js
W_OUT = 3072                      # 3072x1536: ~0.12 deg / texel (1.4 MB; 4096 costs 2.8 MB)


def build_map(exr_path):
    import OpenEXR
    from PIL import Image
    a = OpenEXR.File(str(exr_path)).parts[0].channels['RGB'].pixels.astype(np.float32)
    a = np.clip(a, 0.0, LCLIP)
    e = np.arcsinh(a / L0) / np.arcsinh(LCLIP / L0)
    img = Image.fromarray(np.round(e * 255).astype(np.uint8), 'RGB')
    if img.width != W_OUT:
        img = img.resize((W_OUT, W_OUT // 2), Image.LANCZOS)
    OUT.mkdir(parents=True, exist_ok=True)
    img.save(OUT / 'milkyway.jpg', quality=82, subsampling=2, optimize=True, progressive=True)
    print('milkyway.jpg', (OUT / 'milkyway.jpg').stat().st_size // 1024, 'kB')


def build_bsc(dat_path):
    op = gzip.open if str(dat_path).endswith('.gz') else open
    rows = []
    with op(dat_path, 'rt', encoding='latin-1') as f:
        for line in f:
            line = line.rstrip('\n').ljust(197)
            if not line[75:77].strip():       # 14 entries (novae, non-stellar) have no position
                continue
            ra = 15 * (int(line[75:77]) + int(line[77:79]) / 60 + float(line[79:83]) / 3600)
            dec = int(line[84:86]) + int(line[86:88]) / 60 + int(line[88:90]) / 3600
            if line[83] == '-':
                dec = -dec
            v = float(line[102:107])
            bv = line[109:114].strip()
            bv = float(bv) if bv else None
            rows.append((ra, dec, v, bv))
    rows.sort(key=lambda r: r[2])              # brightest first
    q = np.empty((len(rows), 4), dtype='<i2')
    for i, (ra, dec, v, bv) in enumerate(rows):
        q[i] = (int(round(ra / 360 * 65536)) - 32768,      # RA:  0..360 deg -> int16
                int(round(dec / 90 * 32767)),              # Dec: -90..90 deg
                int(round(v * 1000)),                      # V [mmag]
                -32768 if bv is None else int(round(bv * 1000)))   # B-V [mmag], -32768 = missing
    b64 = base64.b64encode(q.tobytes()).decode()
    js = ('// Yale Bright Star Catalog, 5th rev. ed. (Hoffleit & Warren 1991), J2000.\n'
          '// Generated by scripts/build_sky.py -- do not edit.  %d stars, sorted brightest first.\n'
          '// Little-endian int16 quads: RA*65536/360-32768, Dec*32767/90, V*1000, (B-V)*1000 (-32768 = n/a).\n'
          'export const BSC5_COUNT = %d;\nexport const BSC5_B64 = "%s";\n') % (len(rows), len(rows), b64)
    (OUT / 'bsc5.js').write_text(js)
    print('bsc5.js', len(rows), 'stars,', len(js) // 1024, 'kB')


if __name__ == '__main__':
    build_map(sys.argv[1])
    build_bsc(sys.argv[2])
